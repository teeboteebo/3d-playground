// Captures Bemz's fabric list and the NOCKEBY cover's prices into src/data/bemzFabrics.ts.
// Run by hand: `node scripts/bemz-fabrics.mjs` (about 2-3 minutes, 0.5 s between requests); commit the result.
import { writeFileSync } from 'node:fs';
import { averagePngColour, parseFabricList, parseProduct, scaleFor } from './bemzParse.mjs';

const COVER = 'NOC6'; // IKEA NOCKEBY 3-seat with right chaise
const BASE = 'https://bemz.com';
const HEADERS = { 'user-agent': 'Mozilla/5.0 (compatible; fabric-snapshot)' };
const DELAY_MS = 500;
const OUT = new URL('../src/data/bemzFabrics.ts', import.meta.url);

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const today = () => new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });

async function get(url, init = {}) {
  const res = await fetch(url, { headers: HEADERS, ...init });
  await sleep(DELAY_MS);
  return res;
}

const listRes = await get(`${BASE}/sv-se/fabrics`);
if (!listRes.ok) throw new Error(`fabrics page: HTTP ${listRes.status}`);
const listed = parseFabricList(await listRes.text());
if (listed.length < 100) throw new Error(`only ${listed.length} fabrics found on the fabrics page; has the page changed?`);

const kept = [];
const dropped = [];
for (const f of listed) {
  const article = `${COVER}-${f.code}`;
  // Bemz redirects fabrics it doesn't offer for a cover to the cover's default page, so don't follow redirects
  const res = await get(`${BASE}/sv-se/products/${article}`, { redirect: 'manual' });
  const product = res.status === 200 ? parseProduct(await res.text(), article) : null;
  if (!product) {
    dropped.push(f.code);
    continue;
  }
  const png = await get(`${f.image}&width=8&format=png`);
  if (!png.ok) throw new Error(`swatch ${f.code}: HTTP ${png.status}`);
  const hex = averagePngColour(Buffer.from(await png.arrayBuffer()));
  kept.push({ ...f, hex, ...product, scale: scaleFor(f.family) });
  if (kept.length % 20 === 0) console.log(`${kept.length} kept, ${dropped.length} dropped, ${listed.length} listed...`);
}

const fabric = (f) =>
  `  { code: ${q(f.code)}, family: ${q(f.family)}, colour: ${q(f.colour)}, tier: ${q(f.tier)}, hex: ${q(f.hex)},\n` +
  `    price: ${f.price},${f.salePrice === undefined ? '' : ` salePrice: ${f.salePrice},`}` +
  ` image: ${q(f.image)}, scale: ${f.scale} },\n`;
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

writeFileSync(
  OUT,
  `// Generated by scripts/bemz-fabrics.mjs from bemz.com; do not edit by hand. Re-run the script to refresh.
import type { BemzFabric } from './fabrics';

/** The Bemz cover the prices are for: IKEA NOCKEBY 3-seat with right chaise. */
export const BEMZ_COVER = '${COVER}';
/** When the list and prices were captured. */
export const BEMZ_CHECKED = '${today()}';
/** Every fabric Bemz sells for BEMZ_COVER, in the order of Bemz's fabric page. */
export const BEMZ_FABRICS: BemzFabric[] = [\n${kept.map(fabric).join('')}];\n`,
);
console.log(`listed ${listed.length}, kept ${kept.length}, dropped ${dropped.length}`);
if (dropped.length) console.log(`dropped: ${dropped.join(' ')}`);
